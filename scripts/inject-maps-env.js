/**
 * Writes public Maps API settings for static HTML deploys (Vercel build).
 * Set PUBLIC_GOOGLE_MAPS_API_KEY and optional PUBLIC_GOOGLE_MAPS_MAP_ID in Vercel.
 */
const fs = require('fs');
const path = require('path');

const apiKey =
  process.env.PUBLIC_GOOGLE_MAPS_API_KEY ||
  process.env.GOOGLE_MAPS_API_KEY ||
  process.env.VITE_GOOGLE_MAPS_API_KEY ||
  '';
const mapId =
  process.env.PUBLIC_GOOGLE_MAPS_MAP_ID ||
  process.env.GOOGLE_MAPS_MAP_ID ||
  process.env.VITE_GOOGLE_MAPS_MAP_ID ||
  '';

const outPath = path.join(__dirname, '..', 'assets', 'js', 'maps-public-env.js');
const contents = `/** Generated by scripts/inject-maps-env.js — do not commit secrets; key is injected at build. */
window.MountainEdgeMapsPublicEnv = {
  apiKey: ${JSON.stringify(apiKey)},
  mapId: ${JSON.stringify(mapId)},
};
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(
  'maps-public-env.js written' +
    (apiKey ? ' (API key present)' : ' (no API key — map will use embed fallback)')
);
